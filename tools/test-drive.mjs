// Stage-5/6 check: enter a car with F, drive with W/A/D, drift, traffic + peds present.
import { createRequire } from 'node:module';
import http from 'node:http'; import fs from 'node:fs'; import path from 'node:path';
const { chromium } = createRequire(import.meta.url)('playwright');
const root = path.resolve('game');
const server = http.createServer((req, res) => { const p = path.join(root, req.url.split('?')[0].replace(/\/$/, '/index.html')); fs.readFile(p, (e, d) => { if (e) { res.writeHead(404); res.end(); return; } res.writeHead(200, { 'content-type': p.endsWith('.js') ? 'text/javascript' : p.endsWith('.css') ? 'text/css' : 'text/html' }); res.end(d); }); }).listen(0);
const browser = await chromium.launch(); const page = await browser.newPage({ viewport: +process.argv[2] ? { width: 1280, height: 720 } : { width: 800, height: 450 } });
const errs = []; page.on('pageerror', (e) => errs.push(e.message + ' ' + (e.stack || '').split('\n')[1])); page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
await page.goto(`http://localhost:${server.address().port}/index.html?q=low&nolock`);
await page.waitForFunction(() => window.__G && __G.mode === 'playing', null, { timeout: 90000 });
const st = () => page.evaluate(() => ({ mode: __G.mode, veh: __G.player.vehicle && __G.player.vehicle.model, sp: __G.player.vehicle ? +__G.player.vehicle.speed.toFixed(1) : 0, x: +__G.player.x.toFixed(1), z: +__G.player.z.toFixed(1), cars: __G.vehicles.length, peds: __G.peds.length, moving: __G.vehicles.filter((v) => v.speed > 2).length, f: window.__frames }));
console.log(await st());
await page.evaluate(() => { __G.simSpeed = 2; const v = __G.vehicles.find((v) => v.role === 'parked' && !v.driver); __G.player.x = v.x + 3; __G.player.z = v.z + 1; window.__car = v.id; });
await page.waitForTimeout(500);
await page.keyboard.press('KeyF');
await page.waitForTimeout(4000);
console.log('after F', await st());
await page.keyboard.down('KeyW'); await page.waitForTimeout(4000);
console.log('after W', await st());
await page.screenshot({ path: 'tools/out/drive1.png' });
await page.keyboard.down('KeyD'); await page.keyboard.down('Space'); await page.waitForTimeout(1500);
await page.screenshot({ path: 'tools/out/drive-drift.png' });
await page.keyboard.up('KeyD'); await page.keyboard.up('Space'); await page.keyboard.up('KeyW');
await page.waitForTimeout(3000);
console.log('end', await st());
await page.screenshot({ path: 'tools/out/drive2.png' });
console.log(errs.length ? errs.slice(0, 10).join('\n') : 'no errors');
await browser.close(); server.close();
